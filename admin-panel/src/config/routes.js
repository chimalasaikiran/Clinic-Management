// Fills the `:param` slots of a route pattern, e.g. pathFor(ROUTES.branch, { branchId: 'main' }).
export function pathFor(pattern, params) {
  return pattern.replace(/:(\w+)/g, (_, key) => encodeURIComponent(params[key]))
}
